"""
tests/vldb_eval/scaleout/cluster.py

Deploy and resize the SIESTA stack on the *already-running* Docker Swarm for
the SCALE-OUT experiment (Exp 2).

Placement (uses the swarm's existing node labels / hostnames — no relabeling):
  * anaconda (leader, 12c/64G): siesta-api + spark-master + minio
  * cerberos / pegasus / unicorn (6c/32G each): one spark-worker each → 3
    workers, 18 cores total.

The scale-out axis is the number of Spark executor cores the driver claims
(``spark.cores.max``) with one core per executor (``spark.executor.cores=1``),
so #executors == cores_max, from 3 (one per worker) up to 18.  Those settings
are read once at SparkSession creation (siesta/core/sparkManager.py), so
changing them means re-rendering the stack and re-deploying: swarm then does a
rolling update of *only* siesta-api (fresh driver), leaving the master, workers
and minio untouched — the running swarm keeps its state between sweep points.

Sizing is driven purely by env vars, which requires a config that does NOT pin
spark_driver_memory / spark_executor_memory (those JSON keys would override the
env).  We therefore point SIESTA_CONFIG at config/siesta.scaleout.config.json.

CLI:
    python -m tests.vldb_eval.scaleout.cluster deploy --cores-max 18
    python -m tests.vldb_eval.scaleout.cluster resize --cores-max 6
    python -m tests.vldb_eval.scaleout.cluster status
    python -m tests.vldb_eval.scaleout.cluster down
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
import urllib.request
from pathlib import Path

_REPO = Path(__file__).resolve().parents[3]

STACK_NAME = "siesta"
REGISTRY = "192.168.1.10:5000"
API_IMAGE = f"{REGISTRY}/siesta/api:latest"
SPARK_IMAGE = f"{REGISTRY}/siesta/spark:4.0.1"
LEADER = "anaconda"
N_WORKERS = 3
WORKER_CORES = 6
WORKER_MEM = "28G"

API_HEALTH = "http://localhost:8000/health"
MASTER_JSON = "http://localhost:8085/json/"
DRIVER_UI = "http://localhost:4040"
DRIVER_REST = f"{DRIVER_UI}/api/v1"
STACK_FILE = _REPO / "tests/vldb_eval/scaleout/stack.generated.yml"


# ---------------------------------------------------------------------------
# Stack rendering
# ---------------------------------------------------------------------------

def render_stack(
    *,
    cores_max: int,
    executor_cores: int = 1,
    executor_mem: str = "4g",
    executor_overhead: str = "512m",
    driver_mem: str = "10g",
    shuffle_partitions: int | None = None,
    rpc_max_size_mb: int = 1024,
    worker_cores: int = WORKER_CORES,
    worker_mem: str = WORKER_MEM,
    n_workers: int = N_WORKERS,
    path: Path = STACK_FILE,
) -> Path:
    """Render a swarm stack file for the given Spark sizing.

    `rpc_max_size_mb` raises spark.rpc.message.maxSize (default 128 MB): the
    adaptive query's transient-pair path collects pair rows to the driver and
    re-parallelises them with createDataFrame, which at r10 on few executors
    builds 150-234 MB tasks.  It is passed via PYSPARK_SUBMIT_ARGS, which the
    driver's JVM launch honours, so siesta's code is unchanged.
    """
    shuffle = shuffle_partitions or max(cores_max * 2, 6)
    yaml = f"""# GENERATED by scaleout/cluster.py — do not edit by hand.
# Spark sizing: cores.max={cores_max}, executor.cores={executor_cores}
version: "3.8"

networks:
  siesta-net:
    driver: overlay
    attachable: true

volumes:
  minio-data: {{}}
  spark-ivy-cache: {{}}

services:

  minio:
    image: minio/minio:latest
    environment:
      - MINIO_ROOT_USER=minioadmin
      - MINIO_ROOT_PASSWORD=minioadmin
    command: server /data --console-address ":9001"
    ports:
      - target: 9000
        published: 9000
        mode: host
      - target: 9001
        published: 9001
        mode: host
    volumes:
      - minio-data:/data
    networks:
      - siesta-net
    deploy:
      replicas: 1
      placement:
        constraints:
          - node.hostname == {LEADER}

  spark-master:
    image: {SPARK_IMAGE}
    environment:
      - SPARK_USER=spark
      - PYSPARK_PYTHON=/usr/bin/python3.12
      - SPARK_SUBMIT_OPTS=-Dlog4j.configurationFile=/opt/spark/conf/log4j2.properties
    command:
      - /opt/spark/bin/spark-class
      - org.apache.spark.deploy.master.Master
      - --host
      - spark-master
      - --port
      - '7077'
      - --webui-port
      - '8085'
    ports:
      - target: 8085
        published: 8085
        mode: host
    networks:
      - siesta-net
    deploy:
      replicas: 1
      # dnsrr so `spark-master` resolves to the task's own (bindable) overlay IP
      # — Spark's master binds to --host, which cannot be a service VIP.
      endpoint_mode: dnsrr
      placement:
        constraints:
          - node.hostname == {LEADER}

  spark-worker:
    image: {SPARK_IMAGE}
    environment:
      - SPARK_USER=spark
      - PYSPARK_PYTHON=/usr/bin/python3.12
      - SPARK_SUBMIT_OPTS=-Dlog4j.configurationFile=/opt/spark/conf/log4j2.properties
      - SPARK_WORKER_CORES={worker_cores}
      - SPARK_WORKER_MEMORY={worker_mem}
    command:
      - /opt/spark/bin/spark-class
      - org.apache.spark.deploy.worker.Worker
      - spark://spark-master:7077
      - --webui-port
      - '8082'
    networks:
      - siesta-net
    deploy:
      replicas: {n_workers}
      placement:
        max_replicas_per_node: 1
        constraints:
          - node.hostname != {LEADER}

  siesta-api:
    image: {API_IMAGE}
    hostname: siesta-api
    init: true
    working_dir: /workspace
    environment:
      - SIESTA_PROJECT_ROOT=/workspace
      - SIESTA_CONFIG=/workspace/config/siesta.scaleout.config.json
      - SIESTA_PYTHON_BIN=python3.12
      - PYSPARK_PYTHON=python3.12
      - PYSPARK_DRIVER_PYTHON=python3.12
      - HADOOP_USER_NAME=spark
      - SPARK_USER=spark
      - MPLCONFIGDIR=/tmp/matplotlib
      - SPARK_IVY_DIR=/tmp/.ivy2
      - SPARK_DRIVER_HOST=siesta-api
      - SPARK_DRIVER_PORT=7078
      - SPARK_BLOCKMANAGER_PORT=7079
      - SPARK_DRIVER_MEMORY={driver_mem}
      - SPARK_EXECUTOR_MEMORY={executor_mem}
      - SPARK_EXECUTOR_CORES={executor_cores}
      - SPARK_CORES_MAX={cores_max}
      - SPARK_EXECUTOR_MEMORY_OVERHEAD={executor_overhead}
      - SPARK_SHUFFLE_PARTITIONS={shuffle}
      - "PYSPARK_SUBMIT_ARGS=--conf spark.rpc.message.maxSize={rpc_max_size_mb} pyspark-shell"
    volumes:
      - {_REPO}:/workspace
      - spark-ivy-cache:/tmp/.ivy2
    # host-mode ports so `siesta-api` resolves to the task's overlay IP (via
    # deploy.endpoint_mode: dnsrr), which Spark's driver<->executor channel needs.
    ports:
      - target: 8000
        published: 8000
        mode: host
      - target: 4040
        published: 4040
        mode: host
    networks:
      - siesta-net
    deploy:
      replicas: 1
      endpoint_mode: dnsrr
      placement:
        constraints:
          - node.hostname == {LEADER}
"""
    path.write_text(yaml)
    return path


# ---------------------------------------------------------------------------
# Deploy / resize / teardown
# ---------------------------------------------------------------------------

def _sh(cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
    print("  $", " ".join(cmd))
    return subprocess.run(cmd, check=check, text=True)


def deploy(**sizing) -> None:
    render_stack(**sizing)
    _sh(["docker", "stack", "deploy", "-c", str(STACK_FILE),
         "--with-registry-auth", "--resolve-image", "never", STACK_NAME])


def resize(cores_max: int, executor_cores: int = 1, **extra) -> None:
    """Re-render + redeploy; swarm rolling-updates only siesta-api."""
    deploy(cores_max=cores_max, executor_cores=executor_cores, **extra)


def down() -> None:
    _sh(["docker", "stack", "rm", STACK_NAME], check=False)


# ---------------------------------------------------------------------------
# Health / readiness
# ---------------------------------------------------------------------------

def _get_json(url: str, timeout: float = 4.0) -> dict | None:
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            return json.loads(r.read().decode())
    except Exception:
        return None


def _get_ok(url: str, timeout: float = 4.0) -> bool:
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            return 200 <= r.status < 300
    except Exception:
        return False


def wait_workers(expected: int = N_WORKERS, expected_cores: int | None = None,
                 timeout_s: float = 180.0) -> dict:
    """Wait until the Spark master reports `expected` live workers."""
    t0 = time.time()
    last = None
    while time.time() - t0 < timeout_s:
        j = _get_json(MASTER_JSON)
        if j:
            alive = [w for w in j.get("workers", []) if w.get("state") == "ALIVE"]
            cores = sum(w.get("cores", 0) for w in alive)
            last = {"workers": len(alive), "cores": cores}
            if len(alive) >= expected and (expected_cores is None or cores >= expected_cores):
                print(f"  spark master: {len(alive)} workers, {cores} cores")
                return last
        time.sleep(3)
    raise TimeoutError(f"spark workers not ready in {timeout_s}s (last={last})")


def wait_api(timeout_s: float = 300.0) -> float:
    t0 = time.time()
    while time.time() - t0 < timeout_s:
        if _get_ok(API_HEALTH):
            dt = time.time() - t0
            print(f"  api healthy after {dt:.0f}s")
            return dt
        time.sleep(3)
    raise TimeoutError(f"api /health not ready in {timeout_s}s")


def driver_executors() -> dict | None:
    """Active executors of the live driver (siesta-api's SparkSession)."""
    apps = _get_json(f"{DRIVER_REST}/applications")
    if not apps:
        return None
    app = apps[0]["id"]
    ex = _get_json(f"{DRIVER_REST}/applications/{app}/executors")
    if ex is None:
        return None
    active = [e for e in ex if e.get("id") != "driver" and e.get("isActive")]
    return {"app": app, "executors": len(active),
            "cores": sum(e.get("totalCores", 0) for e in active)}


def running_jobs() -> list[int] | None:
    """Ids of the live driver's running Spark jobs (None if unreachable)."""
    apps = _get_json(f"{DRIVER_REST}/applications")
    if not apps:
        return None
    jobs = _get_json(f"{DRIVER_REST}/applications/{apps[0]['id']}/jobs?status=running")
    if jobs is None:
        return None
    return [j["jobId"] for j in jobs]


def _kill_job(job_id: int) -> None:
    req = urllib.request.Request(f"{DRIVER_UI}/jobs/job/kill/?id={job_id}",
                                 data=b"", method="POST")
    try:
        urllib.request.urlopen(req, timeout=5).read()
    except Exception:
        pass  # the UI answers with a redirect; the job may also have just ended


def ensure_idle(settle_s: float = 8.0, timeout_s: float = 180.0) -> int:
    """Cancel the driver's running Spark jobs until it stays idle for `settle_s`.

    A request the client gave up on (a censored query) keeps running on the
    server and would queue the next measurement behind it.  siesta sets no job
    groups, so the request cannot be cancelled on its own; instead every running
    job is killed through the Spark UI.  Killing one job does not end a request
    (it launches the next), so this loops until no job has run for `settle_s`.
    Returns the number of jobs killed.
    """
    t0 = time.time()
    killed: set[int] = set()
    idle_since = None
    while time.time() - t0 < timeout_s:
        jobs = running_jobs()
        if jobs is None:  # driver unreachable: nothing to cancel
            return len(killed)
        if jobs:
            idle_since = None
            for j in jobs:
                _kill_job(j)
                killed.add(j)
        else:
            idle_since = idle_since or time.time()
            if time.time() - idle_since >= settle_s:
                return len(killed)
        time.sleep(1)
    print(f"  warning: driver not idle after {timeout_s:.0f}s")
    return len(killed)


def wait_executors(expected_cores: int, timeout_s: float = 600.0) -> dict:
    """Wait until the driver holds exactly `expected_cores` executor cores.

    `docker stack deploy` returns before swarm replaces siesta-api, so the old
    driver (sized for the previous point) keeps answering /health for a while;
    a health check alone would let the sweep start on the old driver and then
    lose its requests when swarm kills it.  The old driver cannot match the new
    core count, so this blocks until the new one is up with its executors.
    """
    t0 = time.time()
    last = None
    while time.time() - t0 < timeout_s:
        last = driver_executors()
        if last and last["cores"] == expected_cores:
            print(f"  driver {last['app']}: {last['executors']} executors, "
                  f"{last['cores']} cores")
            return last
        time.sleep(3)
    raise TimeoutError(f"driver not at {expected_cores} cores in {timeout_s}s (last={last})")


def wait_ready(expected_cores: int | None = None, api_timeout_s: float = 300.0) -> dict:
    """Wait for the workers, the driver at the expected size, and the API."""
    w = wait_workers()
    if expected_cores is not None:
        w["driver"] = wait_executors(expected_cores)
    wait_api(timeout_s=api_timeout_s)
    return w


def status() -> None:
    _sh(["docker", "stack", "ps", "--no-trunc", STACK_NAME], check=False)
    j = _get_json(MASTER_JSON)
    if j:
        alive = [x for x in j.get("workers", []) if x.get("state") == "ALIVE"]
        print(f"spark: {len(alive)} alive workers, "
              f"{sum(x.get('cores',0) for x in alive)} cores, "
              f"apps={len(j.get('activeapps', []))}")
    print("api healthy:", _get_ok(API_HEALTH))


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    for name in ("deploy", "resize"):
        p = sub.add_parser(name)
        p.add_argument("--cores-max", type=int, required=True)
        p.add_argument("--executor-cores", type=int, default=1)
        p.add_argument("--executor-mem", default="4g")
        p.add_argument("--driver-mem", default="10g")
        p.add_argument("--wait", action="store_true", help="block until ready")

    sub.add_parser("status")
    sub.add_parser("down")
    sub.add_parser("render").add_argument("--cores-max", type=int, default=18)

    args = ap.parse_args()

    if args.cmd in ("deploy", "resize"):
        deploy(cores_max=args.cores_max, executor_cores=args.executor_cores,
               executor_mem=args.executor_mem, driver_mem=args.driver_mem)
        if args.wait:
            wait_ready(expected_cores=min(args.cores_max, N_WORKERS * WORKER_CORES))
    elif args.cmd == "render":
        print("wrote", render_stack(cores_max=args.cores_max))
    elif args.cmd == "status":
        status()
    elif args.cmd == "down":
        down()


if __name__ == "__main__":
    main()
